/**
 * Android launcher icon definitions — zero dependencies.
 *
 * Every Android icon is rendered from the same first-party mark as the web icons
 * (scripts/icon-mark.mjs), so the APK and the PWA cannot drift apart. This module only
 * describes *which* files Android needs and returns their bytes; writing them to disk is the
 * job of scripts/android/generate-launcher-icons.mjs, which keeps this part unit testable.
 */
import { renderMark, encodePng, MARK_COLORS } from '../icon-mark.mjs';

/** Legacy launcher icons: one PNG per density bucket, in dp the launcher asks for. */
export const LEGACY_ICON_SIZES = [
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
];

/**
 * Adaptive-icon foregrounds are 108dp at every density; only the inner 72dp is guaranteed to
 * be visible after the launcher applies its mask, so the mark is drawn at its natural scale
 * inside that safe zone (see the README note in android/README.md).
 */
export const FOREGROUND_ICON_SIZES = [
  ['mdpi', 108],
  ['hdpi', 162],
  ['xhdpi', 216],
  ['xxhdpi', 324],
  ['xxxhdpi', 432],
];

const ADAPTIVE_LAUNCHER = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android/generate-launcher-icons.mjs — do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;

const LAUNCHER_BACKGROUND = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from scripts/icon-mark.mjs (MARK_COLORS.tileTo) — do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">${MARK_COLORS.tileTo}</color>
</resources>
`;

/**
 * Every generated file, as `{ path, size, buffer }` with `path` relative to
 * `android/app/src/main/res/`.
 */
export function renderLauncherIcons() {
  const files = [];
  for (const [density, size] of LEGACY_ICON_SIZES) {
    files.push({
      path: `mipmap-${density}/ic_launcher.png`,
      size,
      buffer: encodePng(renderMark(size), size),
    });
    files.push({
      path: `mipmap-${density}/ic_launcher_round.png`,
      size,
      buffer: encodePng(renderMark(size, { round: true }), size),
    });
  }
  for (const [density, size] of FOREGROUND_ICON_SIZES) {
    files.push({
      path: `mipmap-${density}/ic_launcher_foreground.png`,
      size,
      buffer: encodePng(renderMark(size, { tile: false }), size),
    });
  }
  return files;
}

/** The adaptive-icon descriptors and the background colour, as `{ path, contents }`. */
export function renderLauncherDescriptors() {
  return [
    { path: 'mipmap-anydpi-v26/ic_launcher.xml', contents: ADAPTIVE_LAUNCHER },
    { path: 'mipmap-anydpi-v26/ic_launcher_round.xml', contents: ADAPTIVE_LAUNCHER },
    { path: 'values/ic_launcher_background.xml', contents: LAUNCHER_BACKGROUND },
  ];
}
